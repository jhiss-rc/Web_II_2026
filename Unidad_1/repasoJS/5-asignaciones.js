// const no cambia de valor
// despues de ser asginado en el espacio de memoria el valor no cambia 
// en ejecucion no cambia luego si
// se usa para operaciones flecha
const nombre = "luis";
console.log(nombre);

const var1 = "juan";
const var2 = "Ruiz";
console.log(var1);
console.log(var2);

//en let el espacio de memoria puede cambiar en ejecucion
// puede concatenar variables
// usado para valores llamados de la BD donde se requiera que cambien
let compuesto = var1 + " " + var2;
console.log(compuesto);